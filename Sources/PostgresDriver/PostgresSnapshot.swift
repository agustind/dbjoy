import DBCore
import Foundation

extension PostgresConnection {
    /// Column default as DDL: identity and generated columns spelled out, so the snapshot
    /// (and table DDL) can recreate them.
    static let columnDefaultSQL = """
        CASE WHEN a.attidentity = 'a' THEN 'GENERATED ALWAYS AS IDENTITY'
             WHEN a.attidentity = 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY'
             WHEN a.attgenerated = 's' THEN 'GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
             ELSE pg_get_expr(d.adbin, d.adrelid) END
        """

    /// Leaves out objects that belong to extensions; installing the extension creates them.
    private static func notFromExtension(_ catalog: String, _ oid: String) -> String {
        "NOT EXISTS (SELECT 1 FROM pg_depend ext WHERE ext.classid = '\(catalog)'::regclass AND ext.objid = \(oid) AND ext.deptype = 'e')"
    }

    /// Plain and partitioned tables, but not partitions, which follow their parent.
    private static var tableFilter: String {
        "c.relkind IN ('r', 'p') AND NOT c.relispartition AND " + notFromExtension("pg_class", "c.oid")
    }

    public func schemaSnapshot(schema: String) async throws -> SchemaSnapshot {
        let extensions = try await query("SELECT extname FROM pg_extension WHERE extname <> 'plpgsql' ORDER BY 1")
            .rows.compactMap { $0[0] }
        let exists = try await query("SELECT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = $1)", parameters: [schema])
            .rows.first?.first.flatMap { $0 } == "true"
        guard exists else { return SchemaSnapshot(schema: schema, exists: false, extensions: extensions) }

        let tables = try await query("""
            SELECT c.relname, obj_description(c.oid, 'pg_class')
            FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = $1 AND \(Self.tableFilter)
            ORDER BY c.relname
            """, parameters: [schema])
        let columns = try await query("""
            SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod), NOT a.attnotnull,
                   \(Self.columnDefaultSQL),
                   col_description(c.oid, a.attnum), a.attnum,
                   EXISTS (SELECT 1 FROM pg_index i WHERE i.indrelid = c.oid AND i.indisprimary AND a.attnum = ANY(i.indkey)),
                   a.attidentity = 'a' OR a.attgenerated <> '', a.attidentity <> ''
            FROM pg_attribute a
            JOIN pg_class c ON c.oid = a.attrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
            WHERE n.nspname = $1 AND \(Self.tableFilter) AND a.attnum > 0 AND NOT a.attisdropped
            ORDER BY c.relname, a.attnum
            """, parameters: [schema])
        let indexes = try await query("""
            SELECT c.relname, i.relname, ix.indisunique, ix.indisprimary, am.amname, pg_get_indexdef(ix.indexrelid),
                   array_to_string(ARRAY(SELECT pg_get_indexdef(ix.indexrelid, k, true)
                                         FROM generate_series(1, ix.indnkeyatts) k), E'\\x1f'),
                   con.conname
            FROM pg_index ix
            JOIN pg_class i ON i.oid = ix.indexrelid
            JOIN pg_class c ON c.oid = ix.indrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            JOIN pg_am am ON am.oid = i.relam
            LEFT JOIN pg_constraint con ON con.conindid = ix.indexrelid AND con.conrelid = ix.indrelid
                                       AND con.contype IN ('p', 'u', 'x')
            WHERE n.nspname = $1 AND \(Self.tableFilter)
            ORDER BY c.relname, ix.indisprimary DESC, i.relname
            """, parameters: [schema])
        let constraints = try await query("""
            SELECT c.relname, con.conname, con.contype::text, pg_get_constraintdef(con.oid, true)
            FROM pg_constraint con
            JOIN pg_class c ON c.oid = con.conrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = $1 AND \(Self.tableFilter) AND con.contype <> 'n'
            ORDER BY c.relname, CASE con.contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'f' THEN 2 ELSE 3 END, con.conname
            """, parameters: [schema])

        let columnsByTable = Dictionary(grouping: columns.rows, by: { $0[0] ?? "" })
        let indexesByTable = Dictionary(grouping: indexes.rows, by: { $0[0] ?? "" })
        let constraintsByTable = Dictionary(grouping: constraints.rows, by: { $0[0] ?? "" })
        let tableStructures = tables.rows.compactMap { row -> TableStructure? in
            guard let name = row[0] else { return nil }
            return TableStructure(
                ref: ObjectRef(schema: schema, name: name, kind: .table),
                columns: (columnsByTable[name] ?? []).map { row in
                    ColumnInfo(name: row[1] ?? "", dataType: row[2] ?? "", isNullable: row[3] == "true",
                               defaultValue: row[4], comment: row[5], ordinal: Int(row[6] ?? "") ?? 0,
                               isPrimaryKey: row[7] == "true", isGenerated: row[8] == "true", isIdentity: row[9] == "true")
                },
                indexes: (indexesByTable[name] ?? []).map { row in
                    IndexInfo(name: row[1] ?? "", columns: (row[6] ?? "").split(separator: "\u{1f}").map(String.init),
                              isUnique: row[2] == "true", isPrimary: row[3] == "true", method: row[4] ?? "",
                              definition: row[5] ?? "", constraintName: row[7])
                },
                constraints: (constraintsByTable[name] ?? []).map { row in
                    ConstraintInfo(name: row[1] ?? "", type: Self.constraintType(row[2] ?? ""), definition: row[3] ?? "")
                },
                comment: row[1])
        }

        return SchemaSnapshot(
            schema: schema, extensions: extensions, tables: tableStructures,
            views: try await views(schema: schema), routines: try await routines(schema: schema),
            enums: try await enums(schema: schema), domains: try await domains(schema: schema),
            sequences: try await sequences(schema: schema), triggers: try await triggers(schema: schema))
    }

    private func views(schema: String) async throws -> [ViewSnapshot] {
        let views = try await query("""
            SELECT c.relname, c.relkind = 'm', pg_get_viewdef(c.oid, true), obj_description(c.oid, 'pg_class')
            FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = $1 AND c.relkind IN ('v', 'm') AND \(Self.notFromExtension("pg_class", "c.oid"))
            ORDER BY c.relname
            """, parameters: [schema])
        let dependencies = try await query("""
            SELECT DISTINCT v.relname, t.relname, a.attname
            FROM pg_rewrite r
            JOIN pg_class v ON v.oid = r.ev_class
            JOIN pg_namespace n ON n.oid = v.relnamespace
            JOIN pg_depend d ON d.objid = r.oid AND d.classid = 'pg_rewrite'::regclass AND d.refclassid = 'pg_class'::regclass
            JOIN pg_class t ON t.oid = d.refobjid
            LEFT JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid AND d.refobjsubid > 0
            WHERE n.nspname = $1 AND v.relkind IN ('v', 'm') AND t.relkind IN ('r', 'p', 'v', 'm', 'f')
              AND t.relnamespace = v.relnamespace AND t.oid <> v.oid
            """, parameters: [schema])
        let columns = try await query("""
            SELECT c.relname, a.attname || ' ' || format_type(a.atttypid, a.atttypmod)
            FROM pg_attribute a
            JOIN pg_class c ON c.oid = a.attrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = $1 AND c.relkind IN ('v', 'm') AND a.attnum > 0 AND NOT a.attisdropped
            ORDER BY c.relname, a.attnum
            """, parameters: [schema])
        let dependenciesByView = Dictionary(grouping: dependencies.rows, by: { $0[0] ?? "" })
        let dependsOn = dependenciesByView.mapValues { Array(Set($0.compactMap { $0[1] })).sorted() }
        let usesColumns = dependenciesByView.mapValues { rows in
            rows.compactMap { row in row[1].flatMap { table in row[2].map { "\(table).\($0)" } } }.sorted()
        }
        let columnsByView = Dictionary(grouping: columns.rows, by: { $0[0] ?? "" }).mapValues { $0.compactMap { $0[1] } }
        return views.rows.compactMap { row in
            guard let name = row[0] else { return nil }
            return ViewSnapshot(name: name, isMaterialized: row[1] == "true",
                                definition: (row[2] ?? "").trimmingCharacters(in: .whitespacesAndNewlines),
                                columns: columnsByView[name] ?? [], dependsOn: dependsOn[name] ?? [],
                                usesColumns: usesColumns[name] ?? [], comment: row[3])
        }
    }

    private func routines(schema: String) async throws -> [RoutineSnapshot] {
        try await query("""
            SELECT p.proname, pg_get_function_identity_arguments(p.oid), p.prokind = 'p', pg_get_functiondef(p.oid)
            FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
            WHERE n.nspname = $1 AND p.prokind IN ('f', 'p') AND \(Self.notFromExtension("pg_proc", "p.oid"))
            ORDER BY 1, 2
            """, parameters: [schema]).rows.compactMap { row in
            guard let name = row[0] else { return nil }
            return RoutineSnapshot(name: name, arguments: row[1] ?? "", isProcedure: row[2] == "true",
                                   definition: (row[3] ?? "").trimmingCharacters(in: .whitespacesAndNewlines))
        }
    }

    private func enums(schema: String) async throws -> [EnumSnapshot] {
        try await query("""
            SELECT t.typname, array_to_string(ARRAY(SELECT e.enumlabel FROM pg_enum e
                                                   WHERE e.enumtypid = t.oid ORDER BY e.enumsortorder), E'\\x1f')
            FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
            WHERE n.nspname = $1 AND t.typtype = 'e' AND \(Self.notFromExtension("pg_type", "t.oid"))
            ORDER BY 1
            """, parameters: [schema]).rows.compactMap { row in
            guard let name = row[0] else { return nil }
            let labels = (row[1] ?? "").isEmpty ? [] : (row[1] ?? "").split(separator: "\u{1f}", omittingEmptySubsequences: false).map(String.init)
            return EnumSnapshot(name: name, labels: labels)
        }
    }

    private func domains(schema: String) async throws -> [DomainSnapshot] {
        try await query("""
            SELECT t.typname, format_type(t.typbasetype, t.typtypmod), t.typdefault, t.typnotnull,
                   array_to_string(ARRAY(SELECT c.conname || E'\\x1e' || pg_get_constraintdef(c.oid, true)
                                         FROM pg_constraint c WHERE c.contypid = t.oid AND c.contype = 'c'
                                         ORDER BY c.conname), E'\\x1f')
            FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
            WHERE n.nspname = $1 AND t.typtype = 'd' AND \(Self.notFromExtension("pg_type", "t.oid"))
            ORDER BY 1
            """, parameters: [schema]).rows.compactMap { row in
            guard let name = row[0] else { return nil }
            let constraints = (row[4] ?? "").split(separator: "\u{1f}").compactMap { item -> ConstraintInfo? in
                let parts = item.split(separator: "\u{1e}", maxSplits: 1).map(String.init)
                return parts.count == 2 ? ConstraintInfo(name: parts[0], type: .check, definition: parts[1]) : nil
            }
            return DomainSnapshot(name: name, baseType: row[1] ?? "", defaultValue: row[2], isNotNull: row[3] == "true",
                                  constraints: constraints)
        }
    }

    private func sequences(schema: String) async throws -> [SequenceSnapshot] {
        // Identity columns own their sequences outright (deptype 'i'); those come with the column.
        try await query("""
            SELECT c.relname, format_type(s.seqtypid, NULL), s.seqstart, s.seqincrement, s.seqmin, s.seqmax,
                   s.seqcache, s.seqcycle, t.relname, a.attname
            FROM pg_sequence s
            JOIN pg_class c ON c.oid = s.seqrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            LEFT JOIN pg_depend d ON d.classid = 'pg_class'::regclass AND d.objid = c.oid
                                 AND d.refclassid = 'pg_class'::regclass AND d.deptype IN ('a', 'i')
            LEFT JOIN pg_class t ON t.oid = d.refobjid
            LEFT JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid
            WHERE n.nspname = $1 AND (d.deptype IS NULL OR d.deptype = 'a')
              AND \(Self.notFromExtension("pg_class", "c.oid"))
            ORDER BY 1
            """, parameters: [schema]).rows.compactMap { row in
            guard let name = row[0] else { return nil }
            return SequenceSnapshot(name: name, dataType: row[1] ?? "bigint", start: row[2] ?? "1", increment: row[3] ?? "1",
                                    minValue: row[4] ?? "1", maxValue: row[5] ?? "", cache: row[6] ?? "1",
                                    cycles: row[7] == "true", ownedByTable: row[8], ownedByColumn: row[9])
        }
    }

    private func triggers(schema: String) async throws -> [TriggerSnapshot] {
        try await query("""
            SELECT c.relname, t.tgname, pg_get_triggerdef(t.oid, true)
            FROM pg_trigger t
            JOIN pg_class c ON c.oid = t.tgrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = $1 AND NOT t.tgisinternal AND t.tgparentid = 0
              AND c.relkind IN ('r', 'p', 'v') AND \(Self.notFromExtension("pg_class", "c.oid"))
            ORDER BY 1, 2
            """, parameters: [schema]).rows.compactMap { row in
            guard let table = row[0], let name = row[1] else { return nil }
            return TriggerSnapshot(table: table, name: name, definition: row[2] ?? "")
        }
    }
}
